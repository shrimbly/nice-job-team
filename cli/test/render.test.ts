// Structural fidelity for the two renderers. The markdown expectations are
// written by hand from the jq -r program's rules (and were checked against
// that jq's own output over the same payloads while being written); the true
// byte-parity proof against the live script belongs to the Integrate step.

import { describe, expect, test } from 'vitest';
import { renderHtml } from '../src/render/html.js';
import { renderMarkdown, summaryLine } from '../src/render/markdown.js';
import type { Card, CardsPayload } from '../src/types.js';

// A tone-"you" card carrying every kind of link, so it appears in "Waiting on
// you" and contributes the three-part Links line.
