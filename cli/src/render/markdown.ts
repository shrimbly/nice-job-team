// board.md, ported from the jq -r program at the bottom of render-board.sh.
// jq -r prints one line per emitted string — embedded \n inside a string come
// out as real newlines — so the port collects emissions and appends the
// newline per emission, exactly what the pipe into board.md received.
//
// Quirks kept on purpose, verified against the jq itself:
// - jq truthiness: only null and false fall through, so `if .num` keeps 0
//   ("#0" renders) and `if .at` keeps "". The `!= null` checks below are that
//   rule exactly, since these fields can never be false.
// - gsub("\\|"; "\\\\|") over-escapes: jq decodes the replacement to TWO
//   backslashes plus the pipe, so a `|` in a table cell becomes `\\|`, not the
//   `\|` the author plainly meant. Parity means reproducing the accident.
// - String slices (`.[0:110]`, `.[0:10]`) count codepoints, where JS .slice
//   counts UTF-16 units — an emoji must cost one step, not two.
// - A linear card always has both key and URL, but jq would interpolate a null
//   ticketKey as the text "null"; template literals do the same, kept as is.

import type { CardsPayload } from '../types.js';

/** The jq `def cell`: null or empty renders as an em dash. */
function cell(v: string | null | undefined): string {
  return v == null || v === '' ? '—' : v;
}

/** jq string slicing is by codepoint; spread before slicing to match. */
function take(s: string, n: number): string {
  return [...s].slice(0, n).join('');
}

export function renderMarkdown(payload: CardsPayload): string {
  const out: string[] = [];

  // jq's sub() replaces the first match only; String.replace with a string
  // pattern does the same.
  out.push('# Board — ' + payload.generatedAt.replace('T', ' ').replace('Z', ' UTC'));
  out.push('');
  out.push('Generated by `render-board.sh`. Do not hand-edit — it is overwritten every cycle.');
  out.push('Live view: `board.html`.');
  out.push('');

  const waiting = payload.cards.filter((c) => c.pill.tone === 'you');
  if (waiting.length > 0) {
    // The trailing \n rides inside the emission, so this heading is followed
    // by a blank line without a separate "" being emitted.
    out.push('## Waiting on you\n');
    out.push(
      waiting
        .map(
          (c) =>
            '- **' +
            c.title +
            '**' +
            (c.num != null ? ` (#${c.num})` : '') +
            ' — ' +
            c.pill.label +
            ', in `' +
            cell(c.workspace) +
            // Two trailing spaces: a markdown hard line break before the
            // indented "where it's at" line.
            '`  \n  ' +
            cell(c.whereItsAt),
        )
        .join('\n'),
    );
    out.push('');
  }

  out.push('## Everything in flight');
  out.push('');
  out.push('| State | Item | PR | Workspace | Where it is |');
  out.push('|---|---|---|---|---|');
  for (const c of payload.cards) {
    out.push(
      '| ' +
        c.pill.label +
        ' | ' +
        c.title +
        ' | ' +
        (c.num != null ? `#${c.num}` : '—') +
        ' | ' +
        cell(c.workspace) +
        // Escape first, truncate after — the cap applies to the escaped text.
        ' | ' +
        take(cell(c.whereItsAt).replace(/\|/g, '\\\\|'), 110) +
        ' |',
    );
  }

  if (payload.recentlyClosed.length > 0) {
    // One emission carrying its own blank lines on both sides, so exactly one
    // blank line separates this heading from the table above and the rows below.
    out.push('\n## Recently closed\n');
    for (const r of payload.recentlyClosed) {
      out.push(
        '- ' +
          r.state +
          ' — ' +
          r.title +
          (r.num != null ? ` (#${r.num})` : '') +
          (r.at != null ? ' on ' + take(r.at, 10) : ''),
      );
    }
  }

  out.push('');
  out.push('## Links');
  out.push('');
  for (const c of payload.cards) {
    if (c.prUrl == null && c.ticketUrl == null && c.previewUrl == null) continue;
    const links: string[] = [];
    if (c.prUrl != null) links.push(`[PR](${c.prUrl})`);
    if (c.ticketUrl != null) links.push(`[${c.ticketKey}](${c.ticketUrl})`);
    if (c.previewUrl != null) links.push(`[preview](${c.previewUrl})`);
    out.push('- ' + c.title + ': ' + links.join(' · '));
  }

  return out.map((line) => line + '\n').join('');
}

/**
 * The script's closing printf, for the CLI to print after writing both files.
 * The counts come from board.json's items — open is everything non-terminal
 * (which is also cards.length), terminal is what the board hides. No trailing
 * newline; console.log supplies it.
 */
export function summaryLine(htmlPath: string, openCards: number, terminalHidden: number): string {
  return `wrote ${htmlPath} and board.md (${openCards} cards, ${terminalHidden} terminal and hidden)`;
}
