export function renderHtml(payload: CardsPayload): string {
  // jq -n pretty-prints with two-space indent, keys in construction order,
  // UTF-8 raw with only the JSON-mandatory escapes — JSON.stringify agrees on
  // all three for this payload. The sed 's|</|<\/|g' then keeps any </script>
  // (or any closing tag) inside a string value from terminating the data
  // block; <\/ is identical JSON.
  const json = JSON.stringify(payload, null, 2).replace(/<\//g, '<\\/');
  // No newline after the JSON: the $(...) capture strips jq's final newline
  // and sed leaves an incomplete last line incomplete, so in the script's
  // output the closing } abuts </script>. Parity keeps the abutment.
  return HTML_HEAD + json + HTML_TAIL;
}
